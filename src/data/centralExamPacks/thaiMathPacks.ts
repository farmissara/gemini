import { CentralExamPack, LearningStrandId, QuizQuestion } from '../../types';

interface CompactPackSeed {
  id: string;
  setNumber: number;
  strand: LearningStrandId;
  titleTh: string;
  titleEn: string;
  gradeLevel: string;
  descriptionTh: string;
  pricingType: 'free' | 'paid';
  priceThb: number;
  publishedAt: string;
  questions: Omit<QuizQuestion, 'id' | 'packId' | 'strand'>[];
}

export function materializeCentralPacks(seeds: CompactPackSeed[]): CentralExamPack[] {
  return seeds.map((seed) => {
    const questions: QuizQuestion[] = seed.questions.map((q, idx) => ({
      ...q,
      id: `${seed.id}-q${idx + 1}`,
      packId: seed.id,
      strand: seed.strand,
    }));

    return {
      id: seed.id,
      titleTh: seed.titleTh,
      titleEn: seed.titleEn,
      strand: seed.strand,
      gradeLevel: seed.gradeLevel,
      descriptionTh: seed.descriptionTh,
      pricingType: seed.pricingType,
      priceThb: seed.pricingType === 'free' ? 0 : seed.priceThb,
      status: 'published',
      questions,
      questionCount: questions.length,
      createdBy: 'Super Admin',
      publishedAt: seed.publishedAt,
      createdAt: seed.publishedAt,
      updatedAt: seed.publishedAt,
    };
  });
}

